MISSING = "##### #...# #...# #...# #...# #...# #####"

def rows(spec):
    out = []
    for r in spec.split():
        bits = 0
        for i, c in enumerate(r):
            if c == '#':
                bits |= 1 << i     # bit i is pixel column i, drawn left to right
        out.append(bits)
    out.append(0)                  # eighth row: descender space
    return out

def main():
    path = os.path.join(os.path.dirname(__file__), '..', 'src', 'host', 'font8x8.h')
    with open(path, 'w') as f:
        f.write("#pragma once\n\n"
                "// Generated by tools/make_font.py -- do not edit.\n"
                "//\n"
                "// A 5x7 font in an 8x8 cell, for ASCII 32..126. Each byte is one row;\n"
                "// bit N of that byte is the pixel N columns from the left.\n\n"
                "#include <cstdint>\n\n"
                "namespace gba::host {\n\n"
                "inline constexpr uint8_t kFont8x8[95][8] = {\n")
        for code in range(32, 127):
            ch = chr(code)
            spec = G.get(ch, MISSING)
            label = 'backslash' if ch == '\\' else ch
            f.write("    {" + ", ".join(f"0x{b:02X}" for b in rows(spec)) + f"}},  // '{label}'\n")
        f.write("};\n\n}  // namespace gba::host\n")
    print(f"wrote {os.path.normpath(path)} ({127-32} glyphs)")

if __name__ == '__main__':
    main()
